-- Winnie Awuor Otieno — portfolio schema (PostgreSQL).
--
-- Applied in order by `npm run migrate`. Each file runs once; the applied
-- versions are recorded in schema_migrations.
--
-- Notes on the port from SQLite:
--   * INTEGER PRIMARY KEY AUTOINCREMENT  ->  IDENTITY (BY DEFAULT, so an
--     explicit id can be supplied when importing existing records)
--   * datetime('now')                    ->  now()
--   * text holding JSON                  ->  jsonb
--   * 0/1 flags                          ->  boolean
--   * TEXT dates                         ->  date
--   * TEXT timestamps                    ->  timestamptz

-- Administrator accounts. No default account is seeded; the first one is
-- created through the protected setup process.
CREATE TABLE IF NOT EXISTS admins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  -- Sealed copy of the password so the administrator can view it in the
  -- panel. Ciphertext only; the key lives in SESSION_SECRET.
  password_ciphertext text NOT NULL DEFAULT '',
  password_updated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Persistent administrator sessions (cookie based).
CREATE TABLE IF NOT EXISTS sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id integer NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sessions_token_hash ON sessions(token_hash);
CREATE INDEX IF NOT EXISTS idx_sessions_expires_at ON sessions(expires_at);
CREATE INDEX IF NOT EXISTS idx_sessions_admin_id ON sessions(admin_id);

-- Media assets. The file itself is never stored here: only its metadata and
-- the storage reference.
CREATE TABLE IF NOT EXISTS media (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_name text NOT NULL,
  -- Storage key, for example profile/9f2c1ab4cd11.png
  storage_name text NOT NULL UNIQUE,
  mime_type text NOT NULL,
  size integer NOT NULL,
  -- Where the file lives, for the filesystem driver. Not a public URL.
  path text NOT NULL DEFAULT '',
  -- Storage bucket, when the object store is used (Supabase Storage or S3).
  bucket text,
  -- public assets are served from a public bucket; private assets are only
  -- ever handed to a signed-in administrator.
  visibility text NOT NULL DEFAULT 'private'
    CHECK (visibility IN ('public', 'private')),
  width integer,
  height integer,
  uploaded_by_admin_id integer REFERENCES admins(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_media_visibility ON media(visibility);
CREATE INDEX IF NOT EXISTS idx_media_created_at ON media(created_at DESC);

-- Singleton public profile settings. One row only.
CREATE TABLE IF NOT EXISTS profile_settings (
  id integer PRIMARY KEY CHECK (id = 1),
  display_name text NOT NULL DEFAULT 'Winnie Awuor Otieno',
  professional_title text NOT NULL DEFAULT 'Accounting, Audit & Tax Professional',
  biography text NOT NULL DEFAULT '',
  location text NOT NULL DEFAULT 'Kisumu, Kenya',
  public_email text NOT NULL DEFAULT '',
  public_phone text NOT NULL DEFAULT '',
  hero_heading text NOT NULL DEFAULT '',
  hero_subheading text NOT NULL DEFAULT '',
  cv_media_id integer REFERENCES media(id) ON DELETE SET NULL,
  profile_image_id integer REFERENCES media(id) ON DELETE SET NULL,
  social_links jsonb NOT NULL DEFAULT '[]'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Employment history.
CREATE TABLE IF NOT EXISTS experience (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position text NOT NULL,
  organization text NOT NULL,
  start_date date NOT NULL,
  end_date date,
  is_current boolean NOT NULL DEFAULT false,
  description text NOT NULL DEFAULT '',
  responsibilities jsonb NOT NULL DEFAULT '[]'::jsonb,
  achievements jsonb NOT NULL DEFAULT '[]'::jsonb,
  display_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_experience_display_order ON experience(display_order);

-- Education and professional qualifications.
CREATE TABLE IF NOT EXISTS education (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institution text NOT NULL,
  qualification text NOT NULL,
  field_of_study text NOT NULL DEFAULT '',
  start_date date,
  end_date date,
  status text NOT NULL DEFAULT 'completed'
    CHECK (status IN ('completed', 'ongoing')),
  description text NOT NULL DEFAULT '',
  display_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_education_display_order ON education(display_order);

-- Areas of expertise.
CREATE TABLE IF NOT EXISTS expertise (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  display_order integer NOT NULL DEFAULT 0,
  is_featured boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_expertise_display_order ON expertise(display_order);

-- Articles and professional insights.
CREATE TABLE IF NOT EXISTS articles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  slug text NOT NULL UNIQUE,
  summary text NOT NULL DEFAULT '',
  body text NOT NULL DEFAULT '',
  featured_image_id integer REFERENCES media(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_articles_slug ON articles(slug);
CREATE INDEX IF NOT EXISTS idx_articles_status ON articles(status);
CREATE INDEX IF NOT EXISTS idx_articles_published_at ON articles(published_at DESC);

-- Contact inquiries from the public contact form. Never exposed publicly.
CREATE TABLE IF NOT EXISTS contact_inquiries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  subject text NOT NULL DEFAULT '',
  message text NOT NULL,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_contact_inquiries_created_at ON contact_inquiries(created_at DESC);

-- Rate limiting counters, shared by every instance of the application.
CREATE TABLE IF NOT EXISTS rate_limits (
  key text PRIMARY KEY,
  count integer NOT NULL DEFAULT 0,
  reset_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_rate_limits_reset_at ON rate_limits(reset_at);

